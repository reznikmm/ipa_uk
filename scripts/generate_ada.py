"""Writes the private package Ukrainian_IPA.Tables from pipeline.pickle."""

import pickle
import sys

import __main__
import build_pipeline

__main__.Stage = build_pipeline.Stage


def ada_character(character: str) -> str:
    return f"WWC'Val (16#{ord(character):04X}#)"


def ada_array(values, per_line=16, indent="      "):
    values = [str(value) for value in values]
    if len(values) == 1:
        return f"[1 => {values[0]}]"
    lines = []
    for start in range(0, len(values), per_line):
        lines.append(indent + ", ".join(values[start : start + per_line]))
    return "[\n" + ",\n".join(lines) + "]"


def main():
    stages = pickle.load(open("pipeline.pickle", "rb"))

    symbols = set()
    for stage in stages:
        for row in stage.transducer.transitions.values():
            symbols |= {chr(label) for label in row}
            symbols |= {character for _, output in row.values() for character in output}
        for output in stage.transducer.final_output.values():
            symbols |= set(output)
    symbols = sorted(symbols)
    symbol_number = {character: index + 1 for index, character in enumerate(symbols)}

    outputs = {"": 1}
    output_symbols = []
    output_start = [1]

    def output_index(text):
        if text not in outputs:
            outputs[text] = len(outputs) + 1
            output_symbols.extend(symbol_number[character] for character in text)
            output_start.append(len(output_symbols) + 1)
        return outputs[text]

    output_start.append(1)  # the empty string: start 1, next start 1

    directions, class_counts, class_of, state_offsets, transition_offsets = [], [], [], [], []
    next_states, transition_outputs, final_outputs = [], [], []
    for stage in stages:
        transducer = stage.transducer
        # renumber states: start state is 1
        order = [transducer.start] + sorted(s for s in transducer.transitions if s != transducer.start)
        local = {state: index + 1 for index, state in enumerate(order)}
        # symbols with identical columns share a class
        columns = {}
        for character in symbols:
            label = ord(character)
            column = tuple(transducer.transitions[state].get(label) for state in order)
            if any(column):
                columns.setdefault(column, []).append(character)
        classes = {}
        for number, members in enumerate(columns.values(), start=1):
            for character in members:
                classes[character] = number
        directions.append("Left_To_Right" if stage.direction == "left to right"
                          else "Right_To_Left")
        class_counts.append(len(columns))
        class_of.append([classes.get(character, 0) for character in symbols])
        state_offsets.append(len(final_outputs))
        transition_offsets.append(len(next_states))
        representative = {number: ord(members[0])
                          for number, members in enumerate(columns.values(), start=1)}
        for state in order:
            row = transducer.transitions[state]
            for number in range(1, len(columns) + 1):
                step = row.get(representative[number])
                if step is None:
                    next_states.append(0)
                    transition_outputs.append(0)
                else:
                    next_states.append(local[step[0]])
                    transition_outputs.append(output_index(step[1]))
            final = transducer.final_output.get(state)
            final_outputs.append(0 if final is None else output_index(final))

    maximal_states = max(stage.transducer.number_of_states() for stage in stages)
    assert maximal_states < 2 ** 16 and len(outputs) < 2 ** 16 and len(symbols) < 2 ** 8

    text = f"""--  Generated by generate_ada.py from the rewrite rules of ipa_uk.ipa
--  (https://github.com/lang-uk/ipa-uk). Do not edit.

pragma Style_Checks (Off);

private package Ukrainian_IPA.Tables is

   pragma Preelaborate;

   subtype WWC is Wide_Wide_Character;

   Symbol_Count : constant := {len(symbols)};

   type Symbol_Index is range 0 .. Symbol_Count with Size => 8;
   --  0 means "not in the alphabet"

   Symbols : constant array (Symbol_Index range 1 .. Symbol_Count) of WWC :=
     {ada_array([ada_character(c) for c in symbols], per_line=4)};
   --  Sorted by code point, for a binary search

   Stage_Count : constant := {len(stages)};

   type Stage_Index is range 1 .. Stage_Count;

   type Direction_Kind is (Left_To_Right, Right_To_Left);

   Direction : constant array (Stage_Index) of Direction_Kind :=
     {ada_array(directions, per_line=3)};

   type Class_Index is range 0 .. {max(class_counts)} with Size => 8;
   --  0 means "no transition on this symbol in this stage"

   Class_Count : constant array (Stage_Index) of Class_Index :=
     {ada_array(class_counts)};

   Class_Of : constant array (Stage_Index, Symbol_Index range 1 .. Symbol_Count)
     of Class_Index :=
     [{", ".join(ada_array(row, indent="       ") for row in class_of)}];

   type State_Index is range 0 .. {maximal_states} with Size => 16;
   --  Numbered inside a stage, 1 is the start state, 0 means "no transition"

   type Output_Index is range 0 .. {len(outputs)} with Size => 16;
   --  0 means "no output" (no transition / not a final state), 1 is ""

   State_Offset : constant array (Stage_Index) of Natural :=
     {ada_array(state_offsets)};
   --  Final_Output (State_Offset (Stage) + Natural (State))

   Transition_Offset : constant array (Stage_Index) of Natural :=
     {ada_array(transition_offsets)};
   --  The transition on class C from state S of a stage is at
   --  Transition_Offset (Stage) + (Natural (S) - 1) * Class_Count (Stage) + C

   Next_State : constant array (1 .. {len(next_states)}) of State_Index :=
     {ada_array(next_states, per_line=20)};

   Transition_Output : constant array (1 .. {len(transition_outputs)}) of Output_Index :=
     {ada_array(transition_outputs, per_line=14)};

   Final_Output : constant array (1 .. {len(final_outputs)}) of Output_Index :=
     {ada_array(final_outputs, per_line=14)};

   Output_Start : constant array (1 .. {len(outputs) + 1}) of Positive :=
     {ada_array(output_start, per_line=12)};
   --  Output text I is Output_Symbols (Output_Start (I) .. Output_Start (I + 1) - 1)

   Output_Symbols : constant array (1 .. {max(len(output_symbols), 1)}) of Symbol_Index :=
     {ada_array(output_symbols or [0], per_line=24)};

end Ukrainian_IPA.Tables;
"""
    with open(sys.argv[1] if len(sys.argv) > 1 else "ukrainian_ipa-tables.ads", "w",
              encoding="utf-8") as file:
        file.write(text)
    print(f"{len(symbols)} symbols, {len(next_states)} transitions, {len(outputs)} outputs, "
          f"{len(output_symbols)} output symbols", file=sys.stderr)


if __name__ == "__main__":
    main()
